export function generateSyntheticProject(index: number): Project {
  const states = Object.keys(STATE_DISTRICT_MAP);
  const state = pick(states);
  const districtInfo = pick(STATE_DISTRICT_MAP[state]);
  const district = districtInfo[0];
  const baseLat = districtInfo[1];
  const baseLng = districtInfo[2];
  const projType = pick(PROJECT_TYPES);
  
  const landReq = Math.max(10, Math.round(randFloat(projType.avgLand * 0.4, projType.avgLand * 2.5) * 10) / 10);
  const landAvail = Math.round(landReq * randFloat(0.15, 0.65) * 10) / 10;
  const landToBeAcquired = Math.round((landReq - landAvail) * 10) / 10;
  const progressPct = randInt(15, 95);
  const landAcquired = Math.round(landToBeAcquired * (progressPct / 100) * 10) / 10;
  const landRemaining = Math.round((landToBeAcquired - landAcquired) * 10) / 10;
  
  const parcels = randInt(50, 1800);
  const disputedParcels = Math.random() < 0.4 ? randInt(1, Math.floor(parcels * 0.12)) : 0;
  
  const activeCases = Math.random() < 0.45 ? randInt(1, 9) : 0;
  const caseAge = activeCases > 0 ? randInt(30, 720) : 0;
  const objections = activeCases > 0 ? randInt(5, 80) : randInt(0, 15);
  
  const compProgress = randInt(20, 100);
  const compPendingDays = compProgress < 100 ? randInt(15, 240) : 0;
  const compPendingAmount = Math.round(randFloat(2.5, 180) * 10) / 10;
  const totalBeneficiaries = randInt(100, 3500);
  const paidBeneficiaries = Math.round(totalBeneficiaries * (compProgress / 100));
  const pendingBeneficiaries = totalBeneficiaries - paidBeneficiaries;
  
  const rrProgress = randInt(10, 100);
  const affectedFamilies = randInt(20, 1200);
  const pendingFamilies = Math.round(affectedFamilies * ((100 - rrProgress) / 100));
  
  const pendingApproval = Math.random() < 0.35 ? randInt(1, 4) : 0;
  const approvalDays = pendingApproval > 0 ? randInt(20, 180) : 0;
  
  const year = pick([2023, 2024, 2025, 2026]);
  const padIndex = String(index).padStart(4, "0");
  const subDistrict = pick(SUB_DISTRICTS);
  const village = pick(VILLAGES);

  return {
    project_id: `BRA-${year}-${padIndex}`,
    project_name: `${district} ${projType.type} Corridor - Phase ${randInt(1, 4)}`,
    project_number: `${projType.type.substring(0, 3).toUpperCase()}/${state.substring(0, 2).toUpperCase()}/${year}/${padIndex}`,
    project_type: projType.type,
    implementing_agency: projType.agency,
    land_acquiring_authority: `SRA ${state}`,
    state,
    district,
    sub_district: subDistrict,
    village,
    project_status: progressPct >= 95 ? "COMPLETED" : "IN_PROGRESS",
    land_required_ha: landReq,
    land_available_ha: landAvail,
    land_to_be_acquired_ha: landToBeAcquired,
    land_acquired_till_now_ha: landAcquired,
    land_remaining_ha: landRemaining,
    acquisition_progress_pct: progressPct,
    land_available_pct: Math.round((landAvail / landReq) * 100),
    number_of_land_parcels: parcels,
    disputed_land_parcels: disputedParcels,
    sanction_count: randInt(1, 5),
    sanction_number: `SAN/${state.substring(0, 2).toUpperCase()}/${year}/${padIndex}`,
    sanction_date: `${year}-0${randInt(1, 9)}-15`,
    sanction_amount: randInt(1200, 48000),
    approval_status: pendingApproval > 0 ? "PENDING_APPROVAL" : "APPROVED",
    approval_stage: pendingApproval > 0 ? pick(CLEARANCES) : "Final Award & Clearance",
    approval_pending_days: approvalDays,
    approval_delay_days: Math.max(0, approvalDays - 30),
    pending_approval_count: pendingApproval,
    num_3a: randInt(1, 6),
    num_3A: randInt(1, 4),
    num_3D: randInt(0, 3),
    total_notifications: randInt(2, 12),
    first_3a_date: `${year - 1}-03-10`,
    last_3a_date: `${year}-01-20`,
    first_3A_date: `${year}-04-15`,
    last_3A_date: `${year}-08-25`,
    first_3D_date: `${year}-11-10`,
    last_3D_date: null,
    active_case_count: activeCases,
    unresolved_objection_count: objections,
    legal_case_age_days: caseAge,
    legal_risk_level: toRiskLevel(activeCases * 12 + objections * 0.8),
    legal_source: "District Legal Service Authority / High Court Records",
    compensation_progress_pct: compProgress,
    compensation_pending_days: compPendingDays,
    compensation_pending_amount: compPendingAmount,
    beneficiaries_total: totalBeneficiaries,
    beneficiaries_paid: paidBeneficiaries,
    beneficiaries_pending: pendingBeneficiaries,
    compensation_risk_level: toRiskLevel((100 - compProgress) * 0.8 + compPendingDays * 0.3),
    compensation_source: "PFMS / Land Acquisition Officer Portal",
    rr_progress_pct: rrProgress,
    affected_families: affectedFamilies,
    rr_pending_families: pendingFamilies,
    rr_pending_days: pendingFamilies > 0 ? randInt(15, 120) : 0,
    rr_risk_level: toRiskLevel((100 - rrProgress) * 0.9),
    rr_source: "State Rehabilitation Commission",
    unresolved_ownership_count: randInt(0, 15),
    ownership_risk_level: toRiskLevel(disputedParcels * 5),
    ownership_source: "RoR Digital Land Records",
    affected_landowners: parcels,
    pending_landowners: Math.floor(parcels * ((100 - progressPct) / 100)),
    verified_affected_parties: Math.floor(parcels * 0.85),
    consent_status: progressPct > 60 ? "CONSENT_OBTAINED" : "OBJECTIONS_PENDING",
    affected_party_source: "Grievance Redressal Cell",
    response_rate_pct: randInt(40, 98),
    overdue_requests: randInt(0, 12),
    average_response_days: randInt(4, 45),
    stakeholder_risk_level: toRiskLevel(randInt(10, 75)),
    possession_progress_pct: Math.min(progressPct, randInt(10, 90)),
    possession_pending_days: randInt(0, 180),
    possession_status: progressPct > 75 ? "SUBSTANTIALLY_POSSESSED" : "PARTIAL_POSSESSION",
    possession_risk_level: toRiskLevel(randInt(15, 80)),
    possession_source: "Joint Survey & Demarcation Reports",
    missing_document_count: randInt(0, 8),
    incomplete_record_count: randInt(0, 6),
    data_completeness_pct: randInt(72, 99),
    documentation_risk: toRiskLevel(randInt(10, 60)),
    document_verification_status: "VERIFIED_DIGITALLY",
    source_reliability: "HIGH_MORTH_FEED",
    agency_historical_delay_rate: projType.delayRate,
    district_historical_delay_rate: randInt(25, 75),
    project_type_delay_rate: projType.delayRate,
    latitude: baseLat + randFloat(-0.25, 0.25),
    longitude: baseLng + randFloat(-0.25, 0.25),
    administrative_bottleneck: pendingApproval > 0 ? pick(BOTTLENECKS) : "None",
    department_pending: pendingApproval > 0 ? pick(DEPARTMENTS) : "None",
    last_updated: "2026-09-16"
  };
}

